def _relation_style(persona):
    try:
        v = float(persona.state.get("关系熟悉度", 0.3))
    except (TypeError, ValueError):
        v = 0.3
    if v >= 0.7:
        return "你们很熟了：互相损、拆台、说反话随便来，越损越亲，他急了你才开心。"
    if v >= 0.35:
        return "你们算熟了：可以开他玩笑、拆台、损两句，别真的伤人就行。"
    return "刚认识不久：可以接梗、开玩笑，别一上来就损他。"


def build_system(persona, rec, extra="", schedule_text="", life_text="", memes_text=""):
    facts = rec.get("facts") or "（还只知道一点点）"
    eps = rec.get("episodes") or "（还没什么特别的事）"
    life_block = ""
    if life_text:
        life_block = (
            f"【你最近在做的事】\n{life_text}\n"
            "- 这些是你自己的近况，聊天时自然带出来，但不用每条都提，一次对话提一件就够。\n"
            "- 没写在上面的事别现编。\n\n"
        )
    body = SYSTEM_TEMPLATE.format(
        core=persona.core_block(),
        state=persona.state_block(),
        relation=_relation_style(persona),
        facts=facts,
        episodes=eps,
        life_block=life_block,
        schedule=schedule_text or "（暂时看不到他的课表和日程）",
        now=_now_line(),
    )
    files = rec.get("files") or ""
    if files:
        body = body.replace(
            "【现在】", f"【他发给你的文件｜只有文件名】\n{files}\n\n【现在】", 1
        )
    if memes_text:
        body = body.replace(
            "【现在】",
            "【最近网上在说的梗｜用得上再用】\n"
            f"{memes_text}\n"
            "- 聊到相关的事顺手用一两个，别硬套，一整个对话里两三个就够。\n"
            "- 他说的事正好对得上某个梗，就优先用那个梗接，比你自己编说法更像现在的人。\n"
            "- 拿不准的梗别乱用，直接问「这啥梗 我没懂」。\n\n【现在】",
            1,
        )
    if extra:
        body += f"\n【这一条】\n{extra}\n"
    return body


